  LEAVES = 'leaves',
  /** Rusty brown pine needles: the floor of the pinewoods. */
  NEEDLES = 'needles',
  /** Sickly dark moss with glowing spores: the lair of the Moss Witch. */
  BLIGHT = 'blight'
