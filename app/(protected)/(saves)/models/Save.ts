import { BaseEntity, Column, Entity } from '@neogroup/neorm'

/**
 * The saved game of a player (one per account). The state of the game lives in
 * `data` (a GameState); the columns are the ones shown in the menu or used to
 * check the writes.
 */
@Entity({ table: 'saves' })
export class Save extends BaseEntity {
  @Column({ primaryKey: true, autoGenerated: true })
  id!: number

  @Column({ cast: 'number' })
  userId!: number

  /** New Game+ cycle: 0 = first playthrough. */
  @Column({ cast: 'number' })
  cycle!: number

  @Column({ cast: 'number' })
  worldVersion!: number

  @Column({ cast: 'number' })
  saveVersion!: number

  /** Increased on every write: a save sent from an outdated copy is rejected (optimistic locking). */
  @Column({ cast: 'number' })
  version!: number

  @Column({ cast: 'number' })
  playTimeSeconds!: number

  /** GameState of the game. */
  @Column({ cast: 'json' })
  data!: unknown

  @Column({ cast: 'date' })
  createdAt!: Date

  @Column({ cast: 'date' })
  updatedAt!: Date
}
